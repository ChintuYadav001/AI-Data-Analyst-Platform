import streamlit as st
import pandas as pd
import io
import json

def render_downloads_view():
    import os
    st.title("📥 Downloads & Artifact Exports")
    st.markdown("Download project synopsis documents, cleaned datasets, SQL scripts, Python notebooks, and audit logs.")

    # Project Synopsis Download Card
    pdf_path = os.path.join(os.getcwd(), "PROJECT_SYNOPSIS.pdf")
    docx_path = os.path.join(os.getcwd(), "PROJECT_SYNOPSIS.docx")
    
    st.markdown("### 🎓 Academic Project Synopsis (CSE-PROJECT-2026-27-04)")
    col_syn_pdf, col_syn_docx = st.columns(2)
    with col_syn_pdf:
        if os.path.exists(pdf_path):
            with open(pdf_path, "rb") as f_pdf:
                st.download_button(
                    label="📄 Download Synopsis PDF (20 Pages)",
                    data=f_pdf.read(),
                    file_name="PROJECT_SYNOPSIS.pdf",
                    mime="application/pdf",
                    type="primary",
                    width="stretch"
                )
    with col_syn_docx:
        if os.path.exists(docx_path):
            with open(docx_path, "rb") as f_docx:
                st.download_button(
                    label="📝 Download Synopsis Word (.docx)",
                    data=f_docx.read(),
                    file_name="PROJECT_SYNOPSIS.docx",
                    mime="application/vnd.openxmlformats-officedocument.wordprocessingml.document",
                    type="secondary",
                    width="stretch"
                )
    
    st.markdown("<hr style='border-color: rgba(255,255,255,0.1); margin: 18px 0;'>", unsafe_allow_html=True)

    if "df" not in st.session_state or st.session_state["df"] is None:
        st.info("ℹ️ Upload a dataset in the 'Upload Dataset' tab to unlock dataset, notebook, and script exports.")
        return

    df = st.session_state["df"]
    raw_df = st.session_state.get("raw_df", df)
    project_name = st.session_state.get("current_project_name", "Dataset")

    c1, c2 = st.columns(2)

    with c1:
        st.markdown("### 📊 Dataset Exports")

        # 1. Cleaned CSV
        csv_data = df.to_csv(index=False).encode('utf-8')
        st.download_button(
            label="⬇️ Download Cleaned CSV",
            data=csv_data,
            file_name=f"{project_name}_cleaned.csv",
            mime="text/csv",
            width="stretch"
        )

        # 2. Cleaned Excel
        excel_buf = io.BytesIO()
        df.to_excel(excel_buf, index=False, engine='openpyxl')
        excel_buf.seek(0)
        st.download_button(
            label="⬇️ Download Cleaned Excel (.xlsx)",
            data=excel_buf,
            file_name=f"{project_name}_cleaned.xlsx",
            mime="application/vnd.openxmlformats-officedocument.spreadsheetml.sheet",
            width="stretch"
        )

        # 3. Original Dataset
        raw_csv = raw_df.to_csv(index=False).encode('utf-8')
        st.download_button(
            label="⬇️ Download Original Dataset (Unmodified)",
            data=raw_csv,
            file_name=f"{project_name}_original.csv",
            mime="text/csv",
            width="stretch"
        )

    with c2:
        st.markdown("### 💻 Code & Script Exports")

        # 4. Python Analysis Script
        py_script = f"""# Auto-generated Python Data Analysis Script for {project_name}
import pandas as pd
import numpy as np

# Load Cleaned Data
df = pd.read_csv('{project_name}_cleaned.csv')
print("Dataset Shape:", df.shape)
print("Column Types:\\n", df.dtypes)
print("Statistical Summary:\\n", df.describe())
"""
        st.download_button(
            label="⬇️ Download Python Analysis Script (.py)",
            data=py_script,
            file_name=f"analyze_{project_name}.py",
            mime="text/x-python",
            width="stretch"
        )

        # 5. Jupyter Notebook (.ipynb)
        nb_json = {
            "cells": [
                {
                    "cell_type": "markdown",
                    "metadata": {},
                    "source": [f"# Exploratory Data Analysis: {project_name}\nAuto-generated by AI Data Analyst Platform."]
                },
                {
                    "cell_type": "code",
                    "execution_count": None,
                    "metadata": {},
                    "outputs": [],
                    "source": [
                        "import pandas as pd\nimport numpy as np\n",
                        f"df = pd.read_csv('{project_name}_cleaned.csv')\n",
                        "df.head()"
                    ]
                }
            ],
            "metadata": {"language_info": {"name": "python"}},
            "nbformat": 4,
            "nbformat_minor": 2
        }
        st.download_button(
            label="⬇️ Download Analytical Notebook (.ipynb)",
            data=json.dumps(nb_json, indent=2),
            file_name=f"{project_name}_notebook.ipynb",
            mime="application/json",
            width="stretch"
        )

        # 6. Cleaning Log History JSON
        log_json = json.dumps(st.session_state.get("cleaning_log", []), indent=2)
        st.download_button(
            label="⬇️ Download Cleaning Audit Log (.json)",
            data=log_json,
            file_name=f"{project_name}_cleaning_log.json",
            mime="application/json",
            width="stretch"
        )
